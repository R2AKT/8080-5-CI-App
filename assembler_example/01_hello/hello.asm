; ============================================================
;  hello.asm — минимальная одиночная программа
;
;  Выводит строку "HELLO" в порт 0x01 и останавливается (HLT).
;  Демонстрирует: ORG, метки, подпрограмму, DB, HLT.
; ============================================================
        ORG 0x0100

start:  LXI  H, msg        ; HL -> адрес строки
        CALL print_str     ; вывести строку
        HLT                ; остановка

; --- подпрограмма: вывод NUL-терминированной строки из HL в порт 0x01 ---
print_str:
loop:   MOV  A, M          ; A = *HL
        ORA  A             ; проверка на NUL
        JZ   done
        OUT  0x01          ; вывод байта
        INX  H             ; HL++
        JMP  loop
done:   RET

; --- данные ---
msg:    DB "HELLO", 0
