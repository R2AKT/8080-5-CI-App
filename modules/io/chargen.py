# ============================================================
# ШРИФТ 8×14 (масштабированный из 8×8)
# ============================================================
def _nearest_scale(glyph, dst_h):
    """Масштабирование глифа по вертикали (nearest neighbour)"""
    src_h = len(glyph)
    if src_h == dst_h:
        return list(glyph)
    return [glyph[r * src_h // dst_h] for r in range(dst_h)]


_DEFAULT_FONT_8x14 = {
    c: _nearest_scale(g, 14) for c, g in _DEFAULT_FONT_8x8.items()
}


# ============================================================
# КЛАСС ЗНАКОГЕНЕРАТОРА
# ============================================================
class CharGenerator:
    """Знакогенератор: код символа → битовая карта"""
    
    def __init__(self):
        self.fonts = {
            8: dict(_DEFAULT_FONT_8x8),
            14: dict(_DEFAULT_FONT_8x14),
        }
        self._cache = {}
    
    def get_bitmap(self, code, height=8):
        """Получить битовую карту символа.
        
        Args:
            code: код символа (0-255)
            height: высота символа (8 или 14)
            
        Returns:
            список байт, каждый байт = строка пикселей (MSB = левый пиксель)
        """
        code &= 0xFF
        key = (code, height)
        if key in self._cache:
            return self._cache[key]
        
        # Выбираем базовый шрифт
        base_h = 8 if height <= 10 else 14
        font = self.fonts.get(base_h, self.fonts[8])
        
        # Получаем глиф
        glyph = font.get(code, font.get(0x20, [0x00] * base_h))
        
        # Масштабируем при необходимости
        if len(glyph) != height:
            glyph = _nearest_scale(glyph, height)
        
        self._cache[key] = glyph
        return glyph
    
    def load_from_file(self, path, height=8, width=8, num_chars=256,
                       invert=False, bit_reverse=False):
        """Загрузить шрифт из файла.
        
        Args:
            path: путь к файлу шрифта
            height: высота глифа в строках (обычно 8)
            width: ширина глифа в пикселях (6 или 8)
            num_chars: количество символов (128 или 256)
            invert: инвертировать биты (0=пиксель, 1=фон)
            bit_reverse: реверс битов (бит 5=левый -> бит 0=левый)
            
        Результат хранится в формате: бит 0 = левый пиксель
        (совместимо с виджетом CRTWidget).
        """
        try:
            with open(path, 'rb') as f:
                data = f.read()
            expected_size = num_chars * height
            if len(data) < expected_size:
                # print(f"[CharGen] ⚠ Файл {path}: ожидалось {expected_size}, получено {len(data)}")
                # self.log(f"[CharGen] ⚠ Файл {path}: ожидалось {expected_size}, получено {len(data)}", 3000)
                return False
            
            font = {}
            for c in range(num_chars):
                start = c * height
                glyph = []
                for row in range(height):
                    byte = data[start + row]
                    # Инверсия (для Радио-86РК: 0=пиксель, 1=фон)
                    if invert:
                        byte = (~byte) & 0xFF
                    # Реверс битов (бит 5=левый -> бит 0=левый)
                    if bit_reverse:
                        byte = self._reverse_bits(byte, width)
                    glyph.append(byte)
                font[c] = glyph
            
            self.fonts[height] = font
            self._cache.clear()
            self._char_width = width
            # print(f"[CharGen] ✅ Загружен шрифт {num_chars}×{width}×{height}, "
                  # f"invert={invert}, reverse={bit_reverse} из {path}")
            # self.log(f"[CharGen] ✅ Загружен шрифт {num_chars}×{width}×{height}, "
                  # f"invert={invert}, reverse={bit_reverse} из {path}")
            return True
        except Exception as e:
            # print(f"[CharGen] ⚠ Ошибка загрузки {path}: {e}")
            # self.log(f"[CharGen] ⚠ Ошибка загрузки {path}: {e}")
            return False
    
    @staticmethod
    def _reverse_bits(byte, width):
        """Реверс младших 'width' битов байта.
        Пример: бит 5=левый -> бит 0=левый (для формат виджета).
        """
        result = 0
        for i in range(width):
            if byte & (1 << i):
                result |= (1 << (width - 1 - i))
        return result
    
    def get_char_width(self):
        """Ширина символа в пикселях (6 или 8)"""
        return getattr(self, '_char_width', 8)

# Глобальный экземпляр знакогенератора
_char_generator = None

def get_char_generator():
    """Получить глобальный экземпляр знакогенератора"""
    global _char_generator
    if _char_generator is None:
        _char_generator = CharGenerator()
    return _char_generator
