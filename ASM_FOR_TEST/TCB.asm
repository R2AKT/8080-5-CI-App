MMU_SEG0	EQU		0x64
MMU_SEG1	EQU		0x65
MMU_SEG2	EQU		0x66
MMU_SEG3	EQU		0x67

SWITCH_CONTEXT::
    DI              				; 1. Запрещаем прерывания на время критической секции

    ; --- ШАГ 1: Сохраняем регистры в стек текущей задачи ---
    PUSH 	PSW						; Сохраняем A и Флаги
    PUSH	B						; Сохраняем BC
    PUSH 	D						; Сохраняем DE
    PUSH 	H						; Сохраняем HL

    ; --- ШАГ 2: Сохраняем SP в TCB текущей задачи ---
    LHLD	CURR_TCB   				; HL = Адрес TCB текущей задачи
    XCHG            				; DE = Адрес TCB текущей задачи
    LXI		H, 0       				; HL = 0
    DAD  	SP         				; HL = Текущее значение SP (трюк 8080 для чтения SP)
    XCHG							; HL = Адрес TCB, DE = Значение SP
    MOV		M,E       				; Записываем младший байт SP по смещению +0
    INX		H
    MOV		M,D       				; Записываем старший байт SP по смещению +1

    ; --- ШАГ 3: Переключаем указатели TCB в планировщике ---
    LHLD	NEXT_TCB   				; HL = Адрес TCB новой задачи
    SHLD	CURR_TCB   				; Теперь новая задача становится текущей

    ; --- ШАГ 4: Переключаем страницы памяти (MMU) под новую задачу ---
    INX		H          				; Смещение +2 (Поле TCB_PAGE_COD)
    MOV		A,M       				; Читаем номер страницы кода для новой задачи
    OUT		0x81       				; Включаем её через порт диспетчера памяти

    ; --- ШАГ 5: Восстанавливаем SP из нового TCB ---
    LHLD	CURR_TCB   				; HL = Базовый адрес нового TCB
    MOV		E,M       				; Читаем младший байт нового SP
    INX		H
    MOV		D,M       				; Читаем старший байт нового SP
    XCHG							; HL = Новый SP
    SPHL							; SP = HL (Стек переключен на память новой задачи!)

    ; --- ШАГ 6: Восстанавливаем регистры из нового стека ---
    POP		H          				; Восстанавливаем H и L новой задачи
    POP		D          				; Восстанавливаем D и E
    POP		B          				; Восстанавливаем B и C
    POP		PSW        				; Восстанавливаем A и Флаги

    EI              				; Разрешаем прерывания
    RET             				; Из стека извлекается сохраненный PC новой задачи.
									; Мы бесшовно вернулись в код нового процесса!

