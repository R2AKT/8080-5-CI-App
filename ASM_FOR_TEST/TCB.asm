CALL_FAR::
    PUSH	A						; Сохраняем аккумулятор
    MVI		A,0x0F					; Номер страницы, где лежит нужная подпрограмма
    OUT		MMU_SEG2				; Подключаем её в Сегмент 2
    POP		A						; Восстанавливаем аккумулятор
    
    CALL	0x8000					; Вызываем функцию по логическому адресу сегмента 2
    
    PUSH	A						; Сохраняем результат
    MVI		A, 0x06					; Возвращаем старую страницу Процесса А
    OUT		MMU_SEG2
    POP		A						; Восстанавливаем результат
    RET

;;
; Вход: HL = Адрес TCB новой задачи
;       DE = Точка входа в программу (Начальный PC)
;       C  = Номер физической страницы памяти для этой задачи
; Переменная NEW_TASK_SP хранит вершину стека новой задачи (например, 0xFFFF)

INIT_TASK::
    PUSH 	H						; Сохраняем адрес TCB в стек ОС
    
    ; --- ШАГ 1: Заполнение TCB ---
    INX  	H
    INX  	H						; Смещение +2 (Поле TCB_PAGE_COD)
    MOV		M,C						; Записываем страницу кода
    INX		H						; Смещение +3 (Поле TCB_PAGE_DAT)
    MOV  	M,C						; Записываем страницу данных
    INX		H						; Смещение +4 (Поле TCB_STATE)
    MVI		M,0x00					; Состояние = 0 (Готова к запуску)

    ; --- ШАГ 2: Имитация стека задачи ---
    ; Временно переключаем MMU на целевую страницу задачи, чтобы подготовить стек
    MOV		A,C
    OUT		MMU_SEG1				; Включили страницу новой задачи в окно данных
    
    LHLD	NEW_TASK_SP				; HL = вершина будущего стека (например, 0xFFFF)
    
    ; Записываем адрес точки входа (PC)
    DCX		H
    MOV		M,D						; Старший байт PC
    DCX		H
    MOV		M,E						; Младший байт PC
    
    ; Записываем 8 байт нулей для регистров (HL, DE, BC, PSW)
    MVI  	B 8						; Счетчик циклов
INIT_STK_LOOP:
    DCX		H
    MVI		M,0x00					; Обнуляем ячейку стека
    DC		B
    JNZ  	INIT_STK_LOOP
    
    ; Теперь HL содержит точное значение SP, готовое для запуска задачи
    XCHG							; Теперь DE = вычисленный SP задачи
    
    ; Возвращаем страницу ОС (предположим, страница 0)
    MVI		A,0x00
    OUT		MMU_SEG1
    
    ; --- ШАГ 3: Фиксация SP в TCB ---
    POP		H						; Возвращаем базовый адрес TCB в HL
    MOV		M,E						; Младший байт SP -> TCB+0
    INX		H
    MOV		M,D						; Старший байт SP -> TCB+1
    RET

;;
; Вход: HL = Адрес TCB новой задачи
; Переменная CURR_TCB хранит адрес текущей работающей задачи

INSERT_TASK:
    PUSH	H
    LHLD	CURR_TCB				; HL = Текущая задача
    LXI		D,6
    DAD		D						; HL указывает на поле NEXT текущей задачи
    MOV		E,M
    INX		H
    MOV		D,M						; DE = Полноценный адрес следующей задачи (старый NEXT)
    
    POP		H						; HL = Новая задача
    PUSH	H
    LXI		B,6
    DAD		B						; HL указывает на поле NEXT новой задачи
    MOV		M,E
    INX		H
    MOV		M,D						; Новая задача теперь указывает на старую следующую
    
    LHLD	CURR_TCB				; HL = Текущая задача
    LXI		D,6
    DAD		D						; HL указывает на NEXT текущей задачи
    POP		D						; DE = Новая задача
    MOV		M,DE					; Текущая задача теперь указывает на новую. Список замкнут!
    RET

;;
TIMER_ISR::
    ; Базовые регистры сохраняются прямо в стек текущей задачи
    PUSH	PSW
    PUSH	B
    PUSH	D
    PUSH	H
;;;;;;;
; Этот код добавляется в самое начало TIMER_ISR (из предыдущего ответа)
DECREMENT_TIMERS:
    LHLD	CURR_TCB				; Начинаем обход с текущей задачи
    MOV		D,H
    MOV		E,L						; Запоминаем стартовую точку для контроля полного круга
    
TIMER_LOOP:
    PUSH	H						; Сохраняем текущий TCB в обходе
    LXI		B,4
    DAD		B						; HL указывает на TCB_STATE
    MOV		A,M
    CPI		0x01					; Задача спит?
    JNZ		NEXT_TIMER_NODE
    
    ; Если спит, уменьшаем счетчик времени (смещение +8)
    POP		H
    PUSH	H
    LXI		B,8
    DAD		B						; HL указывает на TCB_TIMER
    MOV		A,M						; Младший байт
    INX		H
    MOV		B,M						; Старший байт
    DCX		H
    
    ; Двойное декрементирование 16-битного числа на 8080
    MOV		A,E						; Временный буфер
    MOV		A,M
    SUB		M						; Проверка на ноль (на самом деле проще через лоджик)
    ; ... (уменьшаем BC на 1) ...
    ; Предположим, вычли 1, результат в BC. Записываем обратно:
    MOV		M,C
    INX		H
    MOV		M,B
    
    ; Если BC стал равен 0, пробуждаем задачу
    MOV		A,B
    ORA		C
    JNZ		NEXT_TIMER_NODE
    
    ; Пробуждение: меняем статус на 0x00 (Готова)
    POP		H
    PUSH	H
    LXI		B,4
    DAD		B
    MVI		M,0x00					; Задача снова готова к исполнению!

NEXT_TIMER_NODE:
    POP		H						; Восстанавливаем текущий TCB
    LXI		B,6
    DAD		B						; Переходим к TCB_NEXT
    MOV		A,M
    INX		H
    MOV		H,M
    MOV		L,A						; HL = Следующий TCB
    
    ; Проверяем, не сделали ли мы полный круг по списку задач
    MOV		A,H
    CMP		D
    JNZ		TIMER_LOOP
    MOV		A, L
    CMP		E
    JNZ		TIMER_LOOP
    
    ; Все таймеры обновлены, переходим к стандартному выбору задачи
    JMP		FIND_NEXT
;;;;;;;

    ; --- Поиск следующей ГОТОВОЙ задачи в кольцевом списке ---
FIND_NEXT:
    LHLD	CURR_TCB				; HL = Текущий TCB
    LXI		D,6
    DAD		D						; Переходим к полю TCB_NEXT
    MOV		E,M
    INX		H
    MOV		D,M						; DE = Адрес следующего TCB в списке
    
    XCHG							; HL = Адрес следующего TCB
    SHLD	NEXT_TCB				; Временно сохраняем его как кандидата
    
    LXI		D,4						; Смещение до поля TCB_STATE
    DAD		D
    MOV		A,M						; A = Статус задачи (0 = Готова)
    CPI		0x00       
    JZ		ACTIVATE				; Если готова — переключаемся на неё!
    
    ; Если задача спала/ждала ввода-вывода:
    LHLD	NEXT_TCB
    SHLD	CURR_TCB				; Сдвигаем указатель текущей и идем на следующий круг
    JMP		FIND_NEXT

ACTIVATE:
    ; Сбрасываем аппаратный контроллер прерываний (например, i8259 / К559ВН59),
    ; чтобы он знал, что обработка текущего прерывания таймера завершена.
    MVI		A,0x20					; Код EOI (End of Interrupt)
    OUT		0x20					; Отправка в контроллер прерываний

    ; Переходим к стандартной процедуре смены контекста.
    ; Она загрузит SP из NEXT_TCB, сделает POP и выполнит RET/EI.
    JMP		SWITCH_CONTEXT

;;
	ORG		0x0008              	; Вектор прерывания RST 1
SYS_CALL_ENTRY::
    DI								; Запрещаем прерывания на время работы ядра
    PUSH	PSW						; Сохраняем регистры пользователя в его стек
    PUSH	B
    PUSH	D
    PUSH	H

    ; Проверяем код функции в аккумуляторе (он лежит внутри сохраненного PSW)
    ; Но для скорости мы можем передавать код функции прямо перед вызовом.
    CPI		0x01					; Функция 1: Сон (Sleep)
    JZ		API_SLEEP
    CPI		0x02					; Функция 2: Ожидание семафора (Wait)
    JZ		API_SEM_WAIT
    CPI		0x03					; Функция 3: Сигнал семафора (Signal)
    JZ		API_SEM_SIGNAL

    ; Если функция неизвестна — возвращаемся
API_EXIT:
    POP		H
    POP		D
    POP		B
    POP		PSW
    EI
    RET
;;
; Вход: BC = Количество квантов времени, на которое нужно уснуть
API_SLEEP::
    LHLD	CURR_TCB				; HL = Теккущий TCB
    PUSH	H						; Сохраняем адрес для дальнейшего использования
    
    ; Переходим к полю TCB_STATE (+4)
    LXI		D,4
    DAD		D
    MVI		M,0x01					; Устанавливаем статус = 0x01 (Спит)
    
    ; Для простоты структуры мы можем временно использовать регистры задачи в TCB
    ; или завести дополнительное поле счетчика сна TCB_TIMER (+8, +9)
    POP		H
    LXI		D,8						; Смещение до счетчика сна в TCB
    DAD		D
    MOV		M,C						; Сохраняем младший байт времени сна
    INX		H
    MOV		M,B						; Сохраняем старший байт времени сна

    ; Так как текущая задача заблокирована, мы должны немедленно переключить контекст
    JMP		FIND_NEXT				; Переходим в планировщик на поиск новой готовой задачи
;;
; Вход: DE = Адрес структуры семафора
API_SEM_WAIT::
    LDAX	D						; Читаем значение семафора (SEM_VALUE)
    CPI		0x00
    JZ		BLOCK_ON_SEM			; Если 0 — ресурс занят, блокируем текущую задачу
    
    ; Если ресурс свободен, уменьшаем счетчик и возвращаем управление
    DCR		A
    STAX	D						; Сохраняем уменьшенное значение семафора
    JMP		API_EXIT				; Успешный возврат в задачу

BLOCK_ON_SEM:
    ; Переводим текущую задачу в режим ожидания семафора
    LHLD	CURR_TCB
    PUSH	H
    LXI		B,4
    DAD		B
    MVI		M,0x03					; TCB_STATE = 0x03 (Заблокирован семафором)
    
    ; Привязываем задачу к очереди семафора. 
    ; Для этого адрес семафора можно сохранить в TCB (например, смещение +8)
    POP		H
    PUSH	H
    LXI		B,8
    DAD		B
    MOV		M,E
    INX		H
    MOV		M,D						; Теперь TCB помнит, какого семафора он ждет
    
    ; Текущая задача заблокирована. Переключаем контекст!
    JMP		FIND_NEXT
;;
; Вход: DE = Адрес структуры семафора
API_SEM_SIGNAL::
    ; Сначала ищем по всему кольцу TCB задачу, которая заблокирована именно на ЭТОМ семафоре
    LHLD	CURR_TCB
    MOV		B,H
    MOV		C,L						; Запоминаем стартовую точку

SEM_SCAN_LOOP:
    PUSH	H						; Сохраняем проверяемый TCB
    LXI		A,4
    ; Проверяем статус TCB_STATE == 0x03
    ; Проверяем, совпадает ли адрес семафора в TCB(+8) с нашим DE
    ; ... (Проверка условий) ...
    JZ		FOUND_BLOCKED_TASK
    
    ; Если не совпало, идем к следующему TCB через поле NEXT
    POP		H
    ; ... переход к следующему TCB ...
    ; Если сделали полный круг и никого не нашли:
    LDAX	D						; Читаем значение семафора
    INR		A						; Увеличиваем счетчик ресурса
    STAX	D
    JMP		API_EXIT				; Никого не разбудили, просто освободили ресурс

FOUND_BLOCKED_TASK:
    POP		H						; HL = Адрес найденного TCB
    LXI		B,4
    DAD		B
    MVI		M,0x00					; Меняем статус на 0x00 (Готова!). Задача разблокирована.
    
    JMP		API_EXIT				; Возвращаемся. На следующем тике таймера она сможет запуститься.

