;;;
;;Task Control Block (TCB):
;Смещение	Размер	Название поля	Описание
;+0			2 байта	TCB_SP			Указатель стека задачи (SP). Самое важное поле
;+2			1 байт	TCB_PAGE_CODE	Номер физической страницы MMU для сегмента кода задачи
;+3			1 байт	TCB_PAGE_DATA	Номер физической страницы MMU для сегмента данных задачи
;+4			1 байт	TCB_STATE		Состояние задачи (0x0 = Ready, 0x1 = Wait I/O, 0x2 = Sleep, 0x3 = Block, 0xFF = Zombi)
;+5			1 байт	TCB_PRIORITY	Приоритет задачи (для планировщика ОС)
;+6			2 байта	TCB_NEXT		Указатель на следующий TCB в цепочке (для списков планирования)

#target rom
#charset ascii
.asm8080

