    ; MOV  A, C
    ; CPI  4                      ; Выделили все 4 базовые страницы памяти по 16 КБ?
    ; JNZ  alloc_child_ram_loop

    ; ; --- ШАГ 3: ЗЕРКАЛЬНОЕ ПОБАЙТОВОЕ КОПИРОВАНИЕ ПАМЯТИ (Сегменты 0-3) ---
