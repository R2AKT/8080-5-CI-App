;===========================================================================
;
; Запустить: FN, len
;
; Использует 4 байта стека
;
RUN_TARGET:
;
; Восстановить страницу пользователя
;;      LDA     REG_PAGE
;;      STA     PAGEIMAGE
;;      OUT     PAGELATCH
;
;  Переключиться на пользовательский стек
        LHLD    REG_SP          ; вернуться к пользовательскому стеку
        SPHL

        LHLD    REG_PC          ; пользовательский PC
        PUSH    H               ; сохраните пользовательский PC для повторного использования
        LHLD    REG_PSW
        PUSH    H               ; сохраните пользователя a и флаги для pop
;
;  Восстановление регистров
        LHLD    REG_BC
        MOV     B,H
        MOV     C,L
        LHLD    REG_DE
        MOV     D,H
        MOV     E,L
        LHLD    REG_HL
;
;  Восстановите состояние прерывания пользователя
; Не влияйте на SOD, не сбрасывайте int 7.5
        LDA     REG_IM
        ANI     07h             ; оставьте только кусочки маски
        ORI     08h             ; набор масок включить
        SIM                      ; установить/очистить 7.5, 6.5, и 5.5 разрешить
;
        LDA     REG_IM
        ANI     08h
        JZ      RUTT10           ; если пользователь прерывает работу
;
;  Возврат к пользователю с включенными прерываниями
        POP     PSW
        EI                       ; включается после следующей инструкции
        RET
;
; Возврат к пользователю с отключенными прерываниями
RUTT10: 
		POP     PSW
        RET

;===========================================================================
;
; Общая точка продолжения для всех входов монитора
; HL = пользовательский PC, SP = пользовательский стек
; REG_STATE имеет текущее состояние, REG_HL, REG_IM, REG_PSW восстановлены
