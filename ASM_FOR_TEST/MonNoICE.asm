        SHLD    REG_PC
        LXI     H,0
        DAD     SP
        SHLD    REG_SP          ; сохранить указатель стека пользователя
        LXI     SP,MONSTACK     ; и используй вместо этого наш
;
        MOV     H,B
        MOV     L,C
        SHLD    REG_BC
        MOV     H,D
        MOV     L,E
        SHLD    REG_DE
;
;;      LDA     PAGEIMAGE       ; получить текущую страницу пользователя
        XRA     A               ; ...или нет, если цель не загружена
        STA     REG_PAGE        ; сохранить страницу пользователя
;
;  Return registers to master
        JMP     RETURN_REGS

;===========================================================================
;
;  Установите байт (ы): FN, len { (страница, длина, высота, данные), (...)... }
;
; Возврат имеет FN, len, (данные из ячеек памяти)
;
; Если ошибка при вставке (память недоступна для записи), прервать, чтобы вернуть короткие данные
;
; Эта функция используется в основном для установки и очистки точек останова
;
; Использует 2 байта стека
;
SET_BYTES:
;
        LXI     H,COMBUF+1
        MOV     B,M             ; длина = 4*NBYTES
        INX     H
        INR     B
        DCR     B
        MVI     C,0             ; C получает количество вставленных байтов
        JZ      SB90            ; если нет байтов(C=0)
        PUSH    H               ; возвращаемый буфер
;
; Цикл при вставке байтов
SB10:   MOV     A,M             ; страница памяти
        INX     H
;;      STA     PAGEIMAGE
;;      OUT     PAGELATCH       ; установить страницу
        MOV     E,M             ; адрес в DE
        INX     H
        MOV     D,M
        INX     H
;
;  Считывание текущих данных в байтовом местоположении
        LDAX    D               ; считывание текущих данных
        XTHL
        MOV     M,A             ; сохранить в буфере возврата
        INX     H
        XTHL
;
;  Вставить новые данные в расположение байта
        MOV     A,M
        STAX    D               ; установить байт
        LDAX    D               ; считать обратно
        CMP     M               ; сравните с желаемым значением
        JNZ     SB90            ; или если вставить не удалось: прервать
        INX     H
        INR     C               ; еще отсчитайте один байт для возврата
;
        DCR     B
        DCR     B
        DCR     B
        DCR     B
        JNZ     SB10            ; цикл для всех байтов
;
;  Возвращаемый буфер с данными из байтовых местоположений
SB90:   MOV     A,C
        STA     COMBUF+1        ; установите количество возвращаемых байтов
        POP     H               ; очистить стэк
;
;  Вычислите контрольную сумму в буфере и отправьте ведущему, затем вернуться
        JMP     SEND

;===========================================================================
;
;  Ввод с порта: FN, len, Адрес порта Lo, PAhi (=0)
;
IN_PORT:
;
;  Адрес порта равен COMBUF+2 (и неиспользуемому старшему адресу+3)
; ; Постройте "IN PORT" и "RET" вокруг него.
        MVI     A,OP_IN
        STA     COMBUF+1
        MVI     A,OP_RET
        STA     COMBUF+3
;
;  Считывание значения порта
        CALL    COMBUF+1
;
;  Возвращаемый байт считывается как "статус"
        JMP     SEND_STATUS

;===========================================================================
;
;  Вывод на порт: FN, len, Адрес порта Lo, PAhi (=0), данные
;
OUT_PORT:
;
;  Адрес порта равен COMBUF+2, (неиспользуемый высокий адрес+3)
; Данные для записи находятся на COMBUF+4
; Создайте "OUT PORT" и "RET" в combuffer
        MVI     A,OP_OUT
        STA     COMBUF+1
        MVI     A,OP_RET
        STA     COMBUF+3
;
; Получить данные
        LDA     COMBUF+4
;
;  Записать значение в порт
        CALL    COMBUF+1
;
;  Вернуть статус OK
        XRA     A
        JMP     SEND_STATUS
;
