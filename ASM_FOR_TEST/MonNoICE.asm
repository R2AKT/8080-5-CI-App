TARGET_STATUS:
;
        LXI     H,TSTG          ; данные для ответа
        LXI     D,COMBUF+1      ; буфер для возврата
        MVI     B,TSTG_SIZE     ; размер ответа
        MOV     A,B
        STAX    D               ; установите размер в буфере ответов
        INX     D
TS10:   MOV     A,M             ; переместить данные ответа в буфер
        STAX    D
        INX     H
        INX     D
        DCR     B
        JNZ     TS10
;
;  Вычислите контрольную сумму в буфере и отправьте ведущему, затем вернуться
        JMP     SEND

