        MOV     B,A
GLP:    MOV     A,M             ; получить байт для A
        STAX    D               ; сохранить для возврата в буфер
        INX     H
        INX     D
        DCR     B
        JNZ     GLP
;
;  Вычислите контрольную сумму в буфере и отправьте ведущему, затем вернуться
GLP90:  JMP     SEND

;===========================================================================
;
;  Записать в память: FN, len, страница, Alo, Ahi, (len- 3 байта данных)
;
; Использует 2 байта стека
;
WRITE_MEM:
;
;  Установить страницу
;;      LDA     COMBUF+2
;;      STA     PAGEIMAGE
;;      OUT     PAGELATCH
;
; Получить адрес
        LXI     D,COMBUF+5      ; указатель на исходные данные в сообщении
        LHLD    COMBUF+3        ; указатель на пункт назначения
        XCHG
;
        LDA     COMBUF+1        ; количество байт в сообщении
        SBI     3               ; меньше страницы, addrlo, addrhi
        JZ      WLP50           ; выйти, если никто не запрашивал
;
; Запишите указанные байты в локальную память
        MOV     B,A
        PUSH    B               ; сохранить счетчик байтов
WLP10:  MOV     A,M             ; байт от хоста
        STAX    D               ; запись в оперативную память
        INX     H
        INX     D
        DCR     B
        JNZ     WLP10
;
;  Сравните, чтобы увидеть, сработала ли запись
        LXI     D,COMBUF+5      ; указатель на исходные данные в сообщении
        LHLD    COMBUF+3        ; указатель на пункт назначения
        XCHG
        POP     B               ; снова размер
;
;  Сравните указанные байты с локальной памятью
WLP20:  LDAX    D               ; перечитайте то, что мы написали
        CMP     M               ; сравнить с данными хоста
        JNZ     WLP80           ; если сбой записи
        INX     H
        INX     D
        DCR     B
        JNZ     WLP20
;
;  Запись выполнена успешно: статус возврата = 0
WLP50:  XRA     A               ; возвратить состояние = 0
        JMP     WLP90
;
;  Ошибка записи: состояние возврата = 1
WLP80:  MVI      A,1
;
;  Вернуть состояние 
WLP90:  JMP     SEND_STATUS

