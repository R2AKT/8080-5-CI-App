;===========================================================================
; Введите здесь через RST nn для точки останова: PSW, PC сохранены.
; Введите с помощью A=код прерывания = состояние процессора
; Состояние прерывания не изменяется в пользовательской программе
INT_ENTRY:
        STA     REG_STATE       ; сохранить состояние входа
;
;  Могут быть включены прерывания: получите сообщение как можно быстрее, чтобы мы могли связаться
        RIM
        DI                      ; Прерывания не допускаются
        STA     REG_IM          ; сохранит регистр прерывания
;
;  Сохраните регистры в блоке reg для возврата к ведущему
        SHLD    REG_HL          ; сохранить HL
        POP     H               ; ПОЛУЧИТЬ ФЛАГИ В L, НАКОПИТЬ В H
        SHLD    REG_PSW         ; сохранить A и флаги
;
;  Если ввод здесь был по точке останова (состояние =1), создайте резервную копию программы
; счетчик указывает на точку останова/RST инструкции. В противном случае оставьте компьютер в покое.
; (Если ВЫЗОВ используется для точки останова, то сделайте резервную копию на 3 байта)
        POP     H               ;Получить информацию о точке останова/прерывании
        LDA     REG_STATE
        DCR     A
        JNZ     NOTBP           ; Если это не точка останова
        DCX     H               ; Резервное копирование PC до точки останова
NOTBP:  JMP     ENTER_MON       ; HL указывает на код операции точки останова
;
;===========================================================================
;  Основной цикл: ожидание командного кадра от ведущего
MAIN:   LXI     SP,MONSTACK     ; Чистый стек - это счастливый стек
        LXI     H,COMBUF        ; Созданное сообщение здесь
;
;  Первый байт - это код функции
        CALL    GETCHAR         ; Получить функцию (использует 6 байт стека)
        JC      MAIN            ; если таймаут: resync
        CPI     FN_MIN
        JC      MAIN            ; если ниже min: незаконная функция
        MOV     M,A             ; Сохранить код функции
        INX     H
;
;  Второй байт - это количество байтов данных (может быть равно нулю)
        CALL    GETCHAR         ; получить байт длины
        JC      MAIN            ; если таймаут: RESYNC
        CPI     COMBUF_SIZE+1
        JNC     MAIN            ; если слишком длинный: недопустимая длина
        MOV     M,A             ; сохранить длину
        INX     H
        ORA     A
        JZ      MA80            ; пропустить цикл передачи данных, если длина = 0
;
;  Цикл для сбора данных
        MOV     B,A             ; сохранить длину для цикла
MA10:   CALL    GETCHAR         ; получить байт данных
        JC      MAIN            ; если таймаут: RESYNC
        MOV     M,A             ; сохранить байт данных
        INX     H
        DCR     B
        JNZ     MA10
;
;  Получить контрольную сумму
MA80:   CALL    GETCHAR         ; получить контрольную сумму
        JC      MAIN            ; если таймаут: RESYNC
        MOV     C,A             ; сохранить контрольную сумму
;
;  Сравните полученную контрольную сумму с суммой, вычисленной в полученном буфере
; (Сумма должна быть равна 0)
        CALL    CHECKSUM
        ADD     C
        JNZ     MAIN            ; если неверная контрольная сумма 
;
;  Обработайте сообщение.
        LDA     COMBUF+0        ; получить код функции
        CPI     FN_GET_STATUS
        JZ      TARGET_STATUS	; Сформировать состояние
        CPI     FN_READ_MEM
        JZ      READ_MEM		; Читать память
        CPI     FN_WRITE_MEM
        JZ      WRITE_MEM		; Записать в память
        CPI     FN_READ_REGS
        JZ      READ_REGS		; Считать регистры
        CPI     FN_WRITE_REGS
        JZ      WRITE_REGS		; Записать в регистры
        CPI     FN_RUN_TARGET
        JZ      RUN_TARGET		; Выполнить
        CPI     FN_SET_BYTES
        JZ      SET_BYTES		; Установить байты
        CPI     FN_IN
        JZ      IN_PORT			; Читать с порта
        CPI     FN_OUT
        JZ      OUT_PORT		; Вывести в порт
;
;  Ошибка: неизвестная функция.
        MVI     A,FN_ERROR
        STA     COMBUF+0        ; установите функцию как "ERROR"
        MVI     A,1
        JMP     SEND_STATUS     ; значение - это "ERROR"

