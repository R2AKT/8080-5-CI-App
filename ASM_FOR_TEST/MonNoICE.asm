;  Подготовьте буфер возврата: FN (без изменений), LEN, ДАННЫЕ
        LXI     D,COMBUF+1      ; указатель на len, данные
        STAX    D               ; возвращаемая длина =запрошенные данные
        INX     D
        ORA     A
        JZ      GLP90           ; если нет байтов, чтобы получить
;
