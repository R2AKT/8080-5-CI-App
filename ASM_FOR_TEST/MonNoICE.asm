;  Чтение из памяти: FN, len, страница, Alo, Ahi, Nbytes
;
READ_MEM:
;
;  Установить страницу
;;      LDA     COMBUF+2
;;      STA     PAGEIMAGE
;;      OUT     PAGELATCH
;
;  Получить адрес
        LHLD    COMBUF+3
        LDA     COMBUF+5        ; количество байтов, которые нужно получить
