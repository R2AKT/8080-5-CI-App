;===========================================================================
;  Добавьте контрольную сумму в COMBUF и отправьте мастеру
;
; Использует 6 байт стека (не включая обратный адрес: перескочил, не вызван)
;
SEND:   CALL    CHECKSUM        ; получить A=CHECKSUM, HL->checksum location
        CMA
        INR     A
        MOV     M,A             ; хранить отрицательную контрольную сумму
;
;  Отправить буфер ведущему
        LXI     H,COMBUF        ; указатель на данные
        LDA     COMBUF+1        ; объем данных
        ADI     3               ; плюс функция, длина, контрольная сумма
        MOV     B,A             ; сохранить количество для цикла
SND10:  MOV     A,M
        CALL    PUTCHAR         ; отправить байт (используется 6 байт стека)
        INX     H
        DCR     B
        JNZ     SND10
        JMP     MAIN            ; вернуться к основному циклу

;===========================================================================
;  Вычислите контрольную сумму на COMBUF. COMBUF+1 имеет длину данных,
; Также включает байт функции и байт длины
;
; Возвращает:
; A = контрольная сумма 
; HL = указатель на следующий байт в буфере (местоположение контрольной суммы)
; B поцарапан
;
; Использует 2 байта стека, включая обратный адрес
;
CHECKSUM:
        LXI     H,COMBUF        ; указатель на буфер
        LDA     COMBUF+1        ; длина сообщения
        ADI     2               ; плюс функция, длина
        MOV     B,A             ; сохранить количество для цикла
        XRA     A               ; контрольная сумма инициализации равна 0
CHK10:  ADD     M
        INX     H
        DCR     B
        JNZ     CHK10           ; цикл для всех
        RET                     ; возврат с контрольной суммой вA
