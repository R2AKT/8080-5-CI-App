;===========================================================================
;  Получить символ в
;
; Возвращает A=char, CY=0, если данные получены
; CY=1, если время ожидания (0,5 секунды)
;
; Использует 4 байта стека, включая обратный адрес
;
GETCHAR:
        PUSH    D
        LXI     D,8000h                 ;длинный таймаут
gc10:   DCX     D
        MOV     A,D
        ORA     E
        JZ      gc90                    ;выход по таймауту
        IN      SERIAL_STATUS           ;чтение состояния устройства
        ANI     RXRDY
        JZ      gc10                    ;еще не готов.
;
;  Полученные данные: вернуть CY=0. данные в А
        XRA     A                       ;cy=0
        IN      SERIAL_DATA             ;чтение данных
        POP     D
        RET
;
; Тайм-аут: возврат CY=1
gc90:   STC                             ;cy=1
        POP     D
        RET
;
;===========================================================================
;  Вывод символа в А
;
