; =============================================================================
; ПОДПРОГРАММА ЯДРА: ПАРСИНГ MBR И ВЕРИФИКАЦИЯ РАЗДЕЛОВ ДИСКА ЧЕРЕЗ ПДП
; =============================================================================
vfs_init_mbr:
    ; Вход: Вызывается один раз при старте ОС в Ring 0 до включения многозадачности.
    ; Выход: A = 00H (УСПЕХ: Раздел VFS найден на LBA 0x1000),
    ;        Либо код ошибки: A = 0F2H (Невалидная сигнатура MBR 0xAA55),
    ;                         A = 0F3H (Раздел VFS на LBA 0x1000 не обнаружен).

    ; --- ШАГ 1: Монопольный захват CompactFlash ---
    ; Инициализационный вызов мьютекса гарантирует чистоту шины IDE
    CALL cf_acquire_lock        

    ; --- ШАГ 2: Аппаратная ПДП-настройка на чтение Сектора 0 (MBR) ---
    ; Взводим внешний контроллер КР580ВТ57 на Канал 0
    ; Параметры: HL = адрес буфера ядра, BC = 512 байт, D = 00H (Чтение CF -> ОЗУ)
    LXI  H, IDE_SYS_BUFFER      ; Системный секторный буфер ядра (512 байт)
    LXI  B, 512                 ; Считываем ровно 1 сектор MBR
    MVI  D, 00H                 ; Направление: Чтение в ОЗУ Ядра
    CALL dma_start_ch0_transfer ; Внешний модуль ПДП взведен и ждет DRQ0

    ; Программируем порты IDE контроллера диска на чтение Сектора 0
    MVI  A, 0E0H
    OUT  IDE_DRV_HEAD           ; Настройка геометрии: режим LBA (Master Drive)
    MVI  A, 1
    OUT  IDE_SECTOR_CNT         ; Считываем 1 сектор
    
    XRA  A                      ; Абсолютный LBA адрес Сектора 0 = 00000000H
    OUT  IDE_LBA_LOW
    OUT  IDE_LBA_MID
    OUT  IDE_LBA_HIGH
    
    MVI  A, IDE_CMD_READ        ; Выстреливаем команду чтения секторов
    OUT  IDE_CMD_STATUS         ; В этот момент CF дернет DRQ0, ВТ57 заблокирует шину.
                                ; Процессор уходит в ПДП-простой (HOLD) на 0.82 мс.

    ; --- ШАГ 3: Процессор очнулся. Валидация сигнатуры MBR (0xAA55) ---
    LXI  H, IDE_SYS_BUFFER + 510 ; HL указывает на байты сигнатуры (смещение 510-511)
    MOV  A, M
    CPI  MBR_SIGNATURE_L        ; Младший байт равен 0x55?
    JNZ  mbr_err_invalid_sig
    INX  H
    MOV  A, M
    CPI  MBR_SIGNATURE_H        ; Старший байт равен 0xAA?
    JNZ  mbr_err_invalid_sig

    ; --- ШАГ 4: Послотовый парсинг таблицы разделов MBR ---
    ; Таблица разделов начинается со смещения 446 (0x01BE) и содержит 4 записи по 16 байт
    LXI  H, IDE_SYS_BUFFER + 446 ; HL указывает на Запись Раздела №1
    SHLD MBR_ENTRY_PTR          ; Сохранили стартовый адрес записи
    MVI  A, 4
    STA  MBR_SLOT_COUNTER       ; Запустили счетчик слотов на 4 итерации

mbr_parse_slots_loop:
    ; Извлекаем тип раздела (Partition Type ID), находящийся по смещению +4 от начала записи
    LHLD MBR_ENTRY_PTR
    LXI  D, 4
    DAD  D                      ; HL указывает точно на байт типа ФС раздела
    MOV  A, M
    STA  VFS_PART_TYPE          ; Сохранили тип ФС текущего слота
    CPI  00H                    ; Слот пуст/неактивен (0x00)?
    JZ   mbr_next_slot_skip     ; Если пуст — мгновенно пропускаем его

    ; Извлекаем стартовый LBA-адрес раздела (Смещение +8 от начала записи, 4 байта)
    LHLD MBR_ENTRY_PTR
    LXI  D, 8
    DAD  D                      ; HL указывает на младший байт 32-битного числа LBA-старта
    
    MOV  E, M                   ; E = LBA0 (Младший байт адреса старта раздела)
    INX  H
    MOV  D, M                   ; D = LBA1
    INX  H
    MOV  C, M                   ; C = LBA2
    INX  H
    MOV  B, M                   ; B = LBA3 (Старший байт адреса старта раздела)
    
    ; Сверяем, равен ли стартовый сектор раздела требуемому смещению 0x1000?
    ; Переносим константу VFS_REQUIRED_LBA (0x1000) для сравнения в пару HL
    PUSH B                      ; Спрятали LBA2 и LBA3 в стек ядра
    LXI  H, VFS_REQUIRED_LBA    ; HL = 0x1000
    MOV  A, E
    CMP  L                      ; Младший байт адреса старта (E) равен 0x00?
    JNZ  mbr_mismatch_pop_exit
    MOV  A, D
    CMP  H                      ; Следующий байт адреса старта (D) равен 0x10?
    JNZ  mbr_mismatch_pop_exit
    
    POP  B                      ; Извлекли старшие байты LBA обратно в BC
    ; Проверяем, равны ли нулю старшие 16 бит адреса LBA (LBA2 и LBA3 обязаны быть 0000H)
    MOV  A, C
    CPI  00H
    JNZ  mbr_next_slot_skip
    MOV  A, B
    CPI  00H
    JNZ  mbr_next_slot_skip

    ; --- РАЗДЕЛ VFS НА LBA 0x1000 СТРОГО ИДЕНТИФИЦИРОВАН ---
    ; Фиксируем 32-битные физические параметры раздела в глобальные переменные ядра
    MOV  A, E
    STA  VFS_PART_START_L       ; Записали LBA0 в ОЗУ Ядра
    MOV  A, D
    STA  VFS_PART_START_L + 1   ; Записали LBA1 в ОЗУ Ядра
    MOV  A, C
    STA  VFS_PART_START_H       ; Записали LBA2 в ОЗУ Ядра
    MOV  A, B
    STA  VFS_PART_START_H + 1   ; Записали LBA3 в ОЗУ Ядра
    
    CALL cf_release_lock        ; Освобождаем накопитель, закрывая семафор
    MVI  A, 00H                 ; Код возврата: Успех! Логический раздел ФС монтирован
    RET

mbr_mismatch_pop_exit:
    POP  B                      ; Восстановили баланс стека ядра при промахе LBA адреса

mbr_next_slot_skip:
    ; Переходим к следующей 16-байтовой записи таблицы MBR
    LHLD MBR_ENTRY_PTR
    LXI  D, 16                  ; Шаг вперед на 16 байт
    DAD  D
    SHLD MBR_ENTRY_PTR          ; Перезаписали указатель на следующий слот MBR
    
    LDA  MBR_SLOT_COUNTER
    DCR  A                      ; Уменьшаем счетчик оставшихся слотов (4 -> 0)
    STA  MBR_SLOT_COUNTER
    JNZ  mbr_parse_slots_loop   ; Если слоты не кончились — продолжаем сканирование

    ; Если обошли все 4 записи, но раздела со стартом на LBA 0x1000 не обнаружили
    CALL cf_release_lock        ; Сняли мьютекс перед выходом из сисколла ошибки
    MVI  A, 0F3H                ; Код ошибки: Базовый VFS раздел на LBA 0x1000 отсутствует
    RET

mbr_err_invalid_sig:
    CALL cf_release_lock        ; Сняли мьютекс диска
    MVI  A, 0F2H                ; Код ошибки: Неверная сигнатура MBR (диск поврежден/не размечен)
    RET
