    ; INR  E
    ; MOV  A, E
    ; CPI  MAX_PROCS + 1          ; Проверили все 254 процесса?
    ; JNZ  dma_tc_wakeup_loop

    ; ; --- ШАГ 4: Сброс вектора прерывания в КР580ВН59 ---
    ; MVI  A, 020H
    ; OUT  MASTER_8259_CMD        ; Неспецифическая команда EOI для линии IR2

    ; POP  H
    ; POP  D
    ; POP  B
    ; POP  PSW                    ; Восстановили регистры прерванного контекста
    ; EI                          ; Разрешаем вложенные прерывания
    ; RET                         ; Аппаратный возврат в Ring 3
; =============================================================================
; АППАРАТНЫЙ ОБРАБОТЧИК IR2 ВН59 (АДРЕС 0x0050): ДЕМУЛЬТИПЛЕКСОР ПДП (TC РЕГИСТР)
; =============================================================================
;    ORG 0050H
hw_dma_tc_entry:
    PUSH PSW
    PUSH B
    PUSH D
    PUSH H                      ; Теневое сохранение контекста прерванной задачи

    ; --- ШАГ 1: Чтение и атомарный сброс Регистра Статуса КР580ВТ57 ---
    IN   DMA_CMD_STATUS         ; Аккумулятор A = Байт статуса ВТ57 (Флаги TC0-TC3)
    MOV  B, A                   ; Сохраняем считанный статус в регистр B для парсинга

    ; --- ШАГ 2: Тестирование Бита 0 (Флаг TC0 — Канал 0: CompactFlash IDE16) ---
    MOV  A, B
    ANI  01H                    ; Изолируем Бит 0 (Маска 00000001B)
    JNZ  dma_handle_cf_ch0      ; Если Бит 0 = 1 — прерывание прилетело от нашей CF-карты!

    ; --- ШАГ 3: Тестирование Бита 1 (Флаг TC1 — Канал 1: Устройство №2) ---
    MOV  A, B
    ANI  02H                    ; Изолируем Бит 1 (Маска 00000010B)
    JNZ  dma_handle_device_ch1  ; Уходим на драйвер устройства Канала 1

    ; --- ШАГ 4: Тестирование Бита 2 (Флаг TC2 — Канал 2: Устройство №3) ---
    MOV  A, B
    ANI  04H                    ; Изолируем Бит 2 (Маска 00000100B)
    JNZ  dma_handle_device_ch2  ; Уходим на драйвер устройства Канала 2

    ; --- ШАГ 5: Тестирование Бита 3 (Флаг TC3 — Канал 3: Устройство №4) ---
    MOV  A, B
    ANI  08H                    ; Изолируем Бит 3 (Маска 00001000B)
    JNZ  dma_handle_device_ch3  ; Уходим на драйвер устройства Канала 3

    ; Если мы пришли в прерывание, но ни один бит TC не взведен — это ложный тик ПДП
    JMP  dma_tc_exit_eoi

; =============================================================================
; ПОДМОДУЛЬ ОБРАБОТКИ ПРЕРЫВАНИЯ КАНАЛА 0: COMPACTFLASH (IDE16 SWAP)
; =============================================================================
dma_handle_cf_ch0:
    ; Аппаратная проверка физического состояния CompactFlash (прожиг флеш-памяти)
dma_tc_cf_loop:
    IN   IDE_CMD_STATUS
    ANI  080H                   ; Маскируем Бит 7 (BSY — Drive Busy)
    JNZ  dma_tc_cf_loop         ; Ждем окончания внутренней физической записи чипа

    ; Свопинг/Чтение завершены, освобождаем дисковый мьютекс
    XRA  A
    STA  CF_LOCK_VARIABLE       ; Сбросили защелку, CompactFlash свободна!

    ; Сканируем таблицу PCB и возвращаем в ST_READY процессы, ждавшие диск (код 05H)
    LXI  H, PCB_TABLE
    MVI  E, 0                   ; Счетчик PID
dma_cf_wakeup_loop:
    PUSH H
    LXI  D, O_STATUS
	DAD D
	MOV A, M
	CPI ST_WAITING
    JNZ  dma_cf_wakeup_next
    POP  H
	PUSH H
    LXI  D, O_WAIT_CODE
	DAD D
	MOV A, M
	CPI 05H ; W_CF_BUSY?
    JNZ  dma_cf_wakeup_next
    POP  H
	PUSH H
    LXI  D, O_STATUS
	DAD D
	MVI M, ST_READY ; Процесс разбужен!
dma_cf_wakeup_next:
    POP  H
	LXI D, PCB_SIZE
	DAD D
	INR E
	MOV A, E
	CPI MAX_PROCS + 1
    JNZ  dma_cf_wakeup_loop
    
    JMP  dma_tc_exit_eoi

; =============================================================================
; ДРАЙВЕРНЫЕ ЗАГЛУШКИ ДЛЯ ОСТАЛЬНЫХ ТРЕХ УСТРОЙСТВ НА КАНАЛАХ ПДП 1, 2, 3
; =============================================================================
dma_handle_device_ch1:
    ; [Здесь вызывается софтверный бэкэнд обслуживания Канала 1 ПДП]
    ; Например, инкремент счетчиков сетевых пакетов, побудка сетевых потоков.
    JMP  dma_tc_exit_eoi

dma_handle_device_ch2:
    ; [Бэкэнд обслуживания Канала 2 ПДП]
    JMP  dma_tc_exit_eoi

dma_handle_device_ch3:
    ; [Бэкэнд обслуживания Канала 3 ПДП]
    JMP  dma_tc_exit_eoi

; =============================================================================
; ЗАВЕРШЕНИЕ ПРЕРЫВАНИЯ И ВЫХОД В Ring 3
; =============================================================================
dma_tc_exit_eoi:
    MVI  A, 020H
    OUT  MASTER_8259_CMD        ; Посылаем команду неспецифического EOI в КР580ВН59 (линия IR2)

    POP  H
    POP  D
    POP  B
    POP  PSW                    ; Полное восстановление контекста Ring 3 задачи
    EI                          ; Разрешаем вложенные прерывания
    RET                         ; Выход в пользовательское пространство

