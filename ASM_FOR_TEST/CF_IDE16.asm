    ; DAD  D
    ; MOV  A, M
    ; CPI  05H                    ; Процесс ждал именно освобождения CF-карты (W_CF_BUSY)?
    ; JNZ  dma_tc_wakeup_next
    
    ; ; Процесс-заказчик найден! Возвращаем его в карусель планировщика
