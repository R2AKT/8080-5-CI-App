    ; ; Шаг 1: Сброс флага Terminal Count внутри БИС КР580ВТ57
    ; ; Чтение регистра статуса ВТ57 автоматически очищает внутренний триггер прерывания
    ; IN   DMA_CMD_STATUS

    ; ; Шаг 2: Аппаратная проверка физического состояния CompactFlash
    ; ; Если шла операция ЗАПИСИ, диск может быть еще занят внутренним прожигом (BSY=1).
    ; ; Мы опрашиваем статус. Так как ПДП уже отпустил шину, этот опрос идет на полной скорости CPU.
; dma_tc_cf_busy_wait:
    ; IN   IDE_CMD_STATUS
    ; ANI  080H                   ; Маскируем Бит 7 (BSY — Drive Busy)
    ; JNZ  dma_tc_cf_busy_wait    ; Если диск еще занят — делаем микроцикл ожидания.
                                ; ; На флеш-памяти это займет доли миллисекунды, после чего 
                                ; ; диск окончательно освободит аппаратную линию.

    ; ; --- ШАГ 3: ОСВОБОЖДЕНИЕ НАКОПИТЕЛЯ И ПОБУДКА ОЧЕРЕДИ СЛУШАТЕЛЕЙ ---
    ; XRA  A
    ; STA  CF_LOCK_VARIABLE       ; Сбросили семафор диска в 00H — CompactFlash свободна!

    ; ; Сканируем таблицу PCB, возвращая в ST_READY все задачи, ждавшие диск (код 05H)
    ; LXI  H, PCB_TABLE
    ; MVI  E, 0                   ; E = Текущий PID (0..254)

