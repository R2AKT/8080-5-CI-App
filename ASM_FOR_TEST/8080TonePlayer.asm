#code MAIN, 	0800h,*
MainStart:
	LXI 	B,Notes				; Load to BC Notes's address pointer
MainLoop:
;; Tone
	LDAX 	B					; Load A (Note's) from the address pointed by BC
	MOV 	E,A					; Copy A to E (LSB)
	INX 	B					; Increment BC
	LDAX 	B					; Load A (Note's) from the address pointed by BC
	MOV 	D,A					; Copy A to D (MSB)
	; DE = Tone
;; Duration
	INX 	B					; Increment BC
	LDAX 	B					; Load A (Duration's) from the address pointed by BC
	MOV 	L,A					; Copy A to L (LSB)
	INX 	B					; Increment BC
	LDAX 	B					; Load A (Duration's) from the address pointed by BC
	MOV 	H,A					; Copy A to H (MSB)
	; HL = Duration
;; Zero Tone ?
	MOV		A,D					; Copy D to A
	ORA		E					; A = A | E (are both A and E zero?)
	JZ		SkipTone			; Jump to 'SkipTone' if the zero-flag is set.
;; Zero Duration ?
	MOV		A,H					; Copy H to A
	ORA		L					; A = A | L (are both A and L zero?)
	JZ		Stop				; Jump to 'Stop' if the zero-flag is set.
;;
	PUSH	B					; Store BC (address pointer) in stack
	; HL = Duration
	; DE = Tone
	CALL	TONE				; HL - Duration, DE - Tone
	POP		B					; Restore BC (address pointer) from stack
;
GetPause:
	INX 	B					; Increment BC
	LDAX 	B					; Load A (Pause's) from the address pointed by BC
	MOV 	L,A					; Copy A to L (LSB)
	INX 	B					; Increment BC
	LDAX 	B					; Load A (Pause's) from the address pointed by BC
	MOV 	H,A					; Copy A to H (MSB)
	; HL = Pause
;; Zero Pause ?
	MOV		A,H					; Copy H to A
	ORA		L					; A = A | L (are both A and L zero?)
	JZ		Stop				; Jump to 'Stop' if the zero-flag is set.
;
	PUSH	B					; Store BC (address pointer) in stack
	; HL = Pause
	CALL	DELAY_ms			; HL - Pause
	POP		B					; Restore BC (address pointer) from stack
;
	INX 	B					; Increment BC
	JMP		MainLoop			; Next pass
;;
SkipTone:
	; HL = Duration
;; Zero Duration ?
	MOV		A,H					; Copy H to A
	ORA		L					; A = A | L (are both A and L zero?)
	JZ		Stop				; Jump to 'Stop' if the zero-flag is set.
;
	PUSH	B					; Store BC (address pointer) in stack
	; HL = Duration
	CALL	Delay_ms			; Delay (skiped tone)
	POP		B					; Restore BC (address pointer) from stack
	JMP		GetPause
;;
Stop:
;	LXI		H,2000				; HL = Pause (2000ms)
;	CALL	DELAY_ms			; HL - Pause
	JMP		MainStart
	RST		0
	HLT
	JMP		Stop

;;
