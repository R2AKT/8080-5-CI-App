#target rom
#charset ascii
.asm8080

;;#include "kernel_syscall.inc"

; =============================================================================
; ПОЛЬЗОВАТЕЛЬСКАЯ ПРОГРАММА RING 3: КОМАНДНЫЙ ИНТЕРПРЕТАТОР (SHELL)
; Скомпилировано для базового адреса 0x0000 пользовательского пространства
; =============================================================================
#code CODE, 0000h
    ORG 0000H

; Номера системных вызовов (Syscall Numbers API)
SYS_FORK			EQU 0		; Порождение нового процесса (fork)
SYS_EXIT			EQU 1		; Завершение текущего процесса (exit)
SYS_WAITPID			EQU 2 		; Сбор статусов завершенных процессов (waitpid)
SYS_REQUEST_IO		EQU 3		; Захват порта ввода-вывода (request_io)
SYS_RELEASE_IO		EQU 4		; Освобождение порта ввода-вывода (release_io)
SYS_OPEN			EQU 5		; Открытие файла / устройства (open)
SYS_CLOSE			EQU 6		; Закрытие файла / устройства (close)
SYS_READ			EQU 7		; Чтение из дескриптора (read)
SYS_WRITE			EQU 8		; Запись в дескриптор (write)
SYS_CHDIR			EQU 9		; Смена рабочей директории (chdir)
SYS_ALARM			EQU 10		; Постановка POSIX-будильника (alarm)
SYS_SIGACTION		EQU 11		; Регистрация обработчика сигнала (sigaction)
SYS_EXECVE			EQU 12		; Загрузка и запуск нового бинарника (execve)
SYS_OVERLAY_MAP		EQU 13		; Программный маппинг сегментов 4-7 (overlay)
SYS_KILL			EQU 14		; Остановка процесса (kill)
SYS_LSEEK			EQU 15		; Изменение текущей позиции чтения/записи (File Offset) открытого объекта (lseek)
SYS_PIPE			EQU	16		; Работа с пайпами (pipe)
SYS_MUTEX			EQU 17		; Работа мьютексами (mutex)
SYS_COND			EQU	18		; Работа с условными переменными (condition variables)
SYS_SEM_WAIT		EQU 19		; Ожидание семафора (sem_wait)
SYS_SEM_POST		EQU 20		; Постановка семафора (sem_post)
SYS_SOCKET			EQU 21		; Сокет (socket)
SYS_SEND			EQU 22		; Посылка сетевого пакета (send)
SYS_RECV			EQU 23		; Приём сетевого пакета (receive)
SYS_SOCKETPAIR		EQU 24		; Создание пары двунаправленных локальных сокетов внутреннего домена (AF_UNIX) (socketpait)
SYS_NETSTAT			EQU 25		; Вывод информации о сетевых интерфейсах и сокетах (netstat)
SYS_SHUTDOWN		EQU	26		; Завершение сетевого стека и IPC-синхронизации (shutdown)
SYS_OPENPTY 		EQU	27		; Pseudo-TTY / PTY (openpty)
SYS_PTSNAME			EQU	28		; Определения имени файла Slave-устройства (pstname)
SYS_TTYNAME			EQU	29		; Определение имени физического терминала (ttyname)
SYS_IOCTL			EQU	30		; Управление вводом-выводом (ioctl)
SYS_SETSID			EQU	31		; Запуск процесса в новом сеансе (setsid)
DEF_SYS_GETPID		EQU	32			; Идентификатор процесса (sys_getuid)
DEF_SYS_GETPPID		EQU	33			; Идентификатор родительского процесса (sys_getppid)
DEF_SYS_GETUID		EQU	34			; Идентификатор пользователя процесса (sys_getuid)

; Константы ввода-вывода
FD_STDIN         EQU 0
FD_STDOUT        EQU 1
CHAR_CR          EQU 0DH        ; Символ перевода каретки (Enter)
CHAR_LF          EQU 0AH        ; Символ перевода строки

shell_main:
    ; Инициализация локального указателя стека задачи Ring 3
    ; Стек растет сверху вниз от границы Сегмента 3 (0xFFFF)
    LXI  SP, 0FFFFH

shell_repl_loop:
    ; --- ШАГ 1: Вывод приглашения командной строки ---
    MVI  D, FD_STDOUT           ; Вывод в стандартный поток tty0 (экран VT100)
    LXI  H, PROMPT_STR          ; Адрес строки приглашения
    LXI  B, 10                  ; Длина строки "eMMU_OS> " (10 байт)
    MVI  C, SYS_WRITE
    RST  6                      ; Системный вызов ядра

    ; --- ШАГ 2: Посимвольное чтение команды пользователя ---
    LXI  H, CMD_BUFFER          ; HL указывает на начало буфера ввода команды
    MVI  E, 0                   ; E = Счетчик длины введенной строки

shell_read_char_loop:
    PUSH H                      ; Спасаем текущий указатель буфера
    PUSH D                      ; Спасаем счетчик длины

    ; Вызываем SYS_READ для чтения ровно 1 символа с клавиатуры
    MVI  D, FD_STDIN            ; Чтение из tty0 (клавиатура ВВ51А)
    LXI  H, CHAR_BUF            ; Системный буфер под 1 символ в Ring 3
    LXI  B, 1                   ; Читаем ровно 1 байт
    MVI  C, SYS_READ
    RST  6                      ; Вызов ловушки ядра (процесс спит, если буфер пуст)

    POP  D                      ; Восстанавливаем счетчики и указатели
    POP  H
    
    LDA  CHAR_BUF               ; Аккумулятор A = введенный пользователем символ
    MOV  B, A                   ; Сохраняем символ в регистр B

    ; Отображаем введенный символ на экране (VT100 Echo-печать)
    PUSH H
	PUSH D
	PUSH B    ; Сохраняем контекст перед WRITE
    ; ТАК КАК ПРЯМОЙ СИНТАКСИС '!' ЗАПРЕЩЕН, ПЕРЕПИСЫВАЕМ ПОСТРОЧНО ДЛЯ 8080:
    PUSH H
    PUSH D
    PUSH B
    MVI  D, FD_STDOUT
    LXI  H, CHAR_BUF
    LXI  B, 1
    MVI  C, SYS_WRITE
    RST  6                      ; Вывели символ обратно на терминал
    POP  B
    POP  D
    POP  H

    ; Проверяем, не нажал ли пользователь Enter (CR = 0x0D)
    MOV  A, B
    CPI  CHAR_CR
    JZ   shell_command_entered  ; Если Enter — строка набрана!

    ; Записываем легитимный символ в командный буфер
    MOV  M, B
    INX  H                      ; Сдвигаем указатель буфера вперед
    INR  E                      ; Увеличиваем счетчик длины строки
    
    MOV  A, E
    CPI  63                     ; Защита от переполнения (макс длина команды 63 байта)
    JNZ  shell_read_char_loop

shell_command_entered:
    MVI  M, 00H                 ; Завершаем строку команды нулем (\0) для POSIX C-strings
    
    ; Переводим каретку на новую строку на экране VT100 (выводим CR + LF)
    LXI  H, NEWLINE_STR
    MVI  D, FD_STDOUT
    LXI  B, 2
    MVI  C, SYS_WRITE
    RST  6

    ; Если пользователь нажал Enter на пустой строке — просто перезапускаем цикл
    MOV  A, E
    CPI  0
    JZ   shell_repl_loop

    ; --- ШАГ 3: ЖИЗНЕННЫЙ ЦИКЛ ПРОЦЕССА (ВЫЗОВ SYS_FORK) ---
    MVI  C, SYS_FORK
    RST  6                      ; Ядро дублирует текущую задачу!
    
    ; На выходе из сисколла:
    ; В Родителе (Shell): Аккумулятор A = PID созданного ребенка
    ; В Потомке (Child):  Аккумулятор A = 00H
    CPI  00H
    JZ   shell_child_exec_phase ; Если мы Потомок (A=0) — прыгаем на фазу загрузки образа

    ; --- ШАГ 4: ЛОГИКА РОДИТЕЛЯ (ОЖИДАНИЕ И УТИЛИЗАЦИЯ ПОТОМКА) ---
    ; Сохраняем PID ребенка в регистровую пару BC для вызова waitpid
    MOV  C, A                   ; C = PID ребенка
    MVI  B, 0                   ; B = 0 (ищем конкретный PID)
    LXI  H, STATUS_OUT_BUF      ; Куда ядро запишет exit code утилиты после смерти
    MVI  C, SYS_WAITPID
    RST  6                      ; Shell засыпает, пока утилита работает на экране VT100
    
    ; Потомок завершился, Shell проснулся! Возвращаемся на выдачу нового prompt
    JMP  shell_repl_loop

; =============================================================================
; ЛОГИКА ПОТОМКА: ЗАГРУЗКА И ВЫПОЛНЕНИЕ НОВОЙ ПРОГРАММЫ
; =============================================================================
shell_child_exec_phase:
    ; Готовим параметры для вызова execve:
    ; DE = логический адрес пути к бинарнику. В нашем простом Shell буфер CMD_BUFFER
    ;      уже содержит набранный пользователем путь (например, "/bin/ls").
    LXI  D, CMD_BUFFER
    LXI  H, 00000H              ; argv = NULL (для минимальной реализации)
    MVI  C, SYS_EXECVE
    RST  6                      ; Потомок делает EXEC! Ядро затирает эту память.
    
    ; Сюда потомок попадет ТОЛЬКО в том случае, если execve вернул ошибку (файл не найден)
    ; Выводим сообщение "Bad command" и легитимно закрываем поток потомка
    MVI  D, FD_STDOUT
    LXI  H, ERR_BAD_CMD
    LXI  B, 13                  ; Длина "Bad command\r\n"
    MVI  C, SYS_WRITE
    RST  6
    
    ; Потомок обязан сделать добровольный SYS_EXIT, иначе он продолжит выполнять код Shell!
    MVI  C, 127                 ; Код возврата = 127 (POSIX Command not found)
    MVI  C, SYS_EXIT
    RST  6                      ; Потомок умер, родитель (Shell) мгновенно проснется

; =============================================================================
; СЕГМЕНТ ДАННЫХ ПРОГРАММЫ SHELL (НАХОДИТСЯ ВНУТРИ СЕГМЕНТА 0 RING 3)
; =============================================================================
PROMPT_STR:  DB "eMMU_OS> "     ; Приглашение командной строки (10 байт)
NEWLINE_STR: DB 0DH, 0AH        ; Символы перевода строки для VT100 (2 байта)
ERR_BAD_CMD: DB "Bad command", 0DH, 0AH ; Сообщение об ошибке (13 байт)

; Локальные буферы переменного пространства задачи Ring 3
CHAR_BUF:    DB 00H             ; Буфер для посимвольного считывания
STATUS_OUT_BUF: DW 0000H        ; Ячейка сбора exit-статусов для waitpid
CMD_BUFFER:  DS 64              ; 64-байтовый массив накопления строки ввода команды
