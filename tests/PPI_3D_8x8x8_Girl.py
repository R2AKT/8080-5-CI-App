"""
Пляжный танец: силуэт девушки в бикини на 3D-кубе 8×8×8.
Итерация 12.9.

Особенности:
- Двухтональный силуэт: тело (яркость 0.35) и бикини (яркость 1.0)
- 4 кадра пляжной хулы: руки и бёдра двигаются
- Объём: силуэт в 3 слоях по глубине
- Тело рисуется напрямую, бикини — через порты 8255 (окно 8255 показывает активность)

Управление:
  api.mw._cube3d_timer.stop()   — остановить танец
"""
from PySide6.QtCore import QTimer

# =============================================
# ШАГ 1: ПОИСК УСТРОЙСТВ
# =============================================
ppi = None
cube_dev = None

for d in api.system.devices.values():
    cls = type(d).__name__
    if cls == 'I8255' and ppi is None:
        ppi = d
    elif cls == 'Cube3D' and cube_dev is None:
        cube_dev = d

if ppi is None:
    print("❌ 8255 не найден! Добавьте 8255 в профиль.")
    raise SystemExit

print(f"✅ 8255 @ 0x{ppi.base_port:02X}")
if cube_dev is not None:
    print(f"✅ Cube3D: {cube_dev.name}")

# =============================================
# ШАГ 2: ОТКРЫТИЕ ВИДЖЕТА КУБА
# =============================================
from ui.cube3d_widget import Cube3DWidget

if hasattr(api.mw, '_cube3d_widget') and api.mw._cube3d_widget is not None:
    cube_widget = api.mw._cube3d_widget
else:
    target = cube_dev if cube_dev is not None else ppi
    cube_widget = Cube3DWidget(target)
    cube_widget.setWindowTitle("3D Куб 8×8×8 — Пляжный танец")
    cube_widget.resize(640, 600)
    api.mw._cube3d_widget = cube_widget

cube_widget.show()
cube_widget.raise_()
cube_widget.activateWindow()

# Настройка
cube_widget.set_persist(False)          # Без автозатухания
cube_widget.set_color(210, 130, 90)     # Загорелая кожа (тёплый тон)

# =============================================
# ШАГ 3: НАСТРОЙКА 8255
# =============================================
base = ppi.base_port
ppi.io_write(base + 3, 0x80)  # Все порты на выход
print(f"📡 8255 настроен: все порты на выход")

# =============================================
# ШАГ 4: КАДРЫ ПЛЯЖНОГО ТАНЦА
# =============================================
# Каждый кадр: {'body': [...], 'bikini': [...]}
# body   — тело (кожа), рисуется с яркостью 0.35
# bikini — купальник, рисуется через порты с яркостью 1.0
# Строка 0 = верх (голова), строка 7 = низ (ноги).

# Кадр 0: стоит, руки вниз
FRAME_0 = {
    'body': [
        0b00111100,  # голова
        0b01111110,  # плечи + руки
        0b00111100,  # торс
        0b00111100,  # талия
        0b01111110,  # бёдра
        0b00100100,  # ноги
        0b00100100,  # ноги
        0b01100110,  # ступни
    ],
    'bikini': [
        0b00000000,
        0b00000000,
        0b00111100,  # верх купальника (грудь)
        0b00000000,
        0b00111100,  # низ купальника (бёдра)
        0b00000000,
        0b00000000,
        0b00000000,
    ],
}

# Кадр 1: руки вверх
FRAME_1 = {
    'body': [
        0b10011001,  # руки вверх + голова
        0b01111110,  # плечи
        0b00111100,  # торс
        0b00111100,  # талия
        0b01111110,  # бёдра
        0b00100100,  # ноги
        0b00100100,  # ноги
        0b01100110,  # ступни
    ],
    'bikini': FRAME_0['bikini'],
}

# Кадр 2: руки вправо, бёдра влево
FRAME_2 = {
    'body': [
        0b00111100,  # голова
        0b00111111,  # руки вправо
        0b00111100,  # торс
        0b00111100,  # талия
        0b01111100,  # бёдра влево
        0b00100100,  # ноги
        0b00100100,  # ноги
        0b01100110,  # ступни
    ],
    'bikini': [
        0b00000000,
        0b00000000,
        0b00111100,  # верх
        0b00000000,
        0b01111000,  # низ (смещён с бёдрами)
        0b00000000,
        0b00000000,
        0b00000000,
    ],
}

# Кадр 3: руки влево, бёдра вправо
FRAME_3 = {
    'body': [
        0b00111100,  # голова
        0b11111100,  # руки влево
        0b00111100,  # торс
        0b00111100,  # талия
        0b00111110,  # бёдра вправо
        0b00100100,  # ноги
        0b00100100,  # ноги
        0b01100110,  # ступни
    ],
    'bikini': [
        0b00000000,
        0b00000000,
        0b00111100,  # верх
        0b00000000,
        0b00111100,  # низ (смещён с бёдрами)
        0b00000000,
        0b00000000,
        0b00000000,
    ],
}

DANCE_SEQUENCE = [FRAME_0, FRAME_1, FRAME_2, FRAME_3]

# =============================================
# ШАГ 5: ПАРАМЕТРЫ
# =============================================
DANCE_SPEED = 320           # мс на кадр
DEPTH_LAYERS = [3, 4, 5]    # Слои по глубине для объёма
BODY_BRIGHTNESS = 0.35      # Яркость тела (приглушённая)

# =============================================
# ШАГ 6: СОСТОЯНИЕ
# =============================================
frame_idx = [0]

# =============================================
# ШАГ 7: ОТРИСОВКА КАДРА
# =============================================
def render_frame(frame):
    """Отрисовать кадр: тело напрямую (тускло), бикини через порты (ярко)"""
    cube_widget.clear()
    
    # === Тело: рисуем напрямую с приглушённой яркостью ===
    for row in range(8):
        pattern = frame['body'][row]
        y = 7 - row  # Инвертируем: строка 0 = верх (Y=7)
        for x in range(8):
            if pattern & (1 << x):
                for z in DEPTH_LAYERS:
                    cube_widget.brightness[z][y][x] = BODY_BRIGHTNESS
    
    # === Бикини: рисуем через порты 8255 (полная яркость) ===
    for row in range(8):
        pattern = frame['bikini'][row]
        y = 7 - row
        for x in range(8):
            if pattern & (1 << x):
                for z in DEPTH_LAYERS:
                    ppi.io_write(base + 0, x)   # X
                    ppi.io_write(base + 1, y)   # Y
                    ppi.io_write(base + 2, z)   # Z (строб)
    
    cube_widget.update()

# =============================================
# ШАГ 8: АНИМАЦИОННЫЙ ЦИКЛ
# =============================================
def next_frame():
    """Один кадр анимации"""
    frame = DANCE_SEQUENCE[frame_idx[0]]
    render_frame(frame)
    frame_idx[0] = (frame_idx[0] + 1) % len(DANCE_SEQUENCE)
    
    timer = QTimer(api.mw)
    timer.setSingleShot(True)
    timer.timeout.connect(next_frame)
    timer.start(DANCE_SPEED)
    api.mw._cube3d_timer = timer

# =============================================
# ШАГ 9: ЗАПУСК
# =============================================
if hasattr(api.mw, '_cube3d_timer') and api.mw._cube3d_timer is not None:
    try:
        api.mw._cube3d_timer.stop()
    except Exception:
        pass

print("\n🏖 Пляжный танец запущен:")
print("   • Двухтональный силуэт: тело темнее, бикини ярче")
print("   • 4 кадра хулы: руки и бёдра двигаются")
print("   • Объём: силуэт в 3 слоях по глубине")
print("   • Бикини рисуется через порты 8255")
print("\n📌 Управление:")
print("   • Вращайте куб мышью!")
print("   • Пробел — переворот, стрелки — поворот")
print("\n⏹ Остановка танца:")
print("   api.mw._cube3d_timer.stop()")

next_frame()
