# -*- coding: utf-8 -*-
"""
Постоянный тест ALU 8080: проверка флагов Z/S/P/C/AC для основных операций.

Опкоды (стандарт 8080, ALU в битах 5-3, регистр в битах 0-2):
  ADD B=0x80  ADC B=0x88  SUB B=0x90  SBB B=0x98
  ANA B=0xA0  XRA B=0xA8  ORA B=0xB0  CMP B=0xB8
  ADI=0xC6  ACI=0xCE  SUI=0xD6  SBI=0xDE
  ANI=0xE6  XRI=0xEE  ORI=0xF6  CPI=0xFE
  DAA=0x27  RLC=0x07  RRC=0x0F  RAL=0x17  RAR=0x1F
  MVI A=0x3E  MVI B=0x06  STC=0x37  CMC=0x3F  HLT=0x76
"""
import os, sys
sys.stdout.reconfigure(encoding='utf-8', errors='replace')
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from i8080_emulator import I8080Emulator

passed = failed = 0

def run_prog(bytes_seq):
    mem = {}
    for i, b in enumerate(bytes_seq):
        mem[0x0100 + i] = b
    emu = I8080Emulator(mem)
    emu.set_pc(0x0100)
    n = 0
    while not emu.halted and n < 50:
        emu.step()
        n += 1
    return emu

def check(name, emu, exp_a=None, exp_z=None, exp_s=None, exp_p=None, exp_c=None, exp_ac=None):
    global passed, failed
    ok = True
    detail = []
    if exp_a is not None and emu.a != exp_a:
        ok = False; detail.append(f"A=0x{emu.a:02X}!=0x{exp_a:02X}")
    if exp_z is not None and emu.flag_z != exp_z:
        ok = False; detail.append(f"Z={emu.flag_z}!={exp_z}")
    if exp_s is not None and emu.flag_s != exp_s:
        ok = False; detail.append(f"S={emu.flag_s}!={exp_s}")
    if exp_p is not None and emu.flag_p != exp_p:
        ok = False; detail.append(f"P={emu.flag_p}!={exp_p}")
    if exp_c is not None and emu.flag_cy != exp_c:
        ok = False; detail.append(f"C={emu.flag_cy}!={exp_c}")
    if exp_ac is not None and emu.flag_ac != exp_ac:
        ok = False; detail.append(f"AC={emu.flag_ac}!={exp_ac}")
    if ok:
        passed += 1
        print(f"  ✅ {name}")
    else:
        failed += 1
        print(f"  ❌ {name}: {', '.join(detail)}")

# --- ADD B (0x80) ---
check("ADD B: 0F+01", run_prog([0x3E,0x0F,0x06,0x01,0x80,0x76]), exp_a=0x10, exp_c=False, exp_ac=True, exp_z=False, exp_s=False)
check("ADD B: FF+01", run_prog([0x3E,0xFF,0x06,0x01,0x80,0x76]), exp_a=0x00, exp_c=True, exp_z=True, exp_s=False)
check("ADD B: 80+80", run_prog([0x3E,0x80,0x06,0x80,0x80,0x76]), exp_a=0x00, exp_c=True, exp_z=True)

# --- ADC B (0x88) ---
check("ADC B: 0F+01+C0", run_prog([0x3E,0x0F,0x06,0x01,0x88,0x76]), exp_a=0x10, exp_ac=True, exp_c=False)
check("ADC B: 0F+01+C1", run_prog([0x3E,0x0F,0x06,0x01,0x37,0x88,0x76]), exp_a=0x11, exp_ac=True, exp_c=False)
check("ADC B: FF+01+C1", run_prog([0x3E,0xFF,0x06,0x01,0x37,0x88,0x76]), exp_a=0x01, exp_c=True)

# --- SUB B (0x90) ---
check("SUB B: 05-03", run_prog([0x3E,0x05,0x06,0x03,0x90,0x76]), exp_a=0x02, exp_c=False, exp_z=False)
check("SUB B: 03-05", run_prog([0x3E,0x03,0x06,0x05,0x90,0x76]), exp_a=0xFE, exp_c=True, exp_s=True)
check("SUB B: 05-05", run_prog([0x3E,0x05,0x06,0x05,0x90,0x76]), exp_a=0x00, exp_c=False, exp_z=True)

# --- SBB B (0x98) ---
check("SBB B: 05-03-C0", run_prog([0x3E,0x05,0x06,0x03,0x98,0x76]), exp_a=0x02, exp_c=False)
check("SBB B: 05-03-C1", run_prog([0x3E,0x05,0x06,0x03,0x37,0x98,0x76]), exp_a=0x01, exp_c=False)
check("SBB B: 03-05-C1", run_prog([0x3E,0x03,0x06,0x05,0x37,0x98,0x76]), exp_a=0xFD, exp_c=True, exp_s=True)

# --- ANA B (0xA0) ---
check("ANA B: 0F&03", run_prog([0x3E,0x0F,0x06,0x03,0xA0,0x76]), exp_a=0x03, exp_ac=False, exp_z=False)
check("ANA B: 0F&08", run_prog([0x3E,0x0F,0x06,0x08,0xA0,0x76]), exp_a=0x08, exp_ac=True)
check("ANA B: FF&00", run_prog([0x3E,0xFF,0x06,0x00,0xA0,0x76]), exp_a=0x00, exp_z=True, exp_ac=False)

# --- XRA B (0xA8) ---
check("XRA B: 0F^03", run_prog([0x3E,0x0F,0x06,0x03,0xA8,0x76]), exp_a=0x0C, exp_z=False)
check("XRA B: FF^FF", run_prog([0x3E,0xFF,0x06,0xFF,0xA8,0x76]), exp_a=0x00, exp_z=True)

# --- ORA B (0xB0) ---
check("ORA B: 05|03", run_prog([0x3E,0x05,0x06,0x03,0xB0,0x76]), exp_a=0x07, exp_z=False)
check("ORA B: 00|00", run_prog([0x3E,0x00,0x06,0x00,0xB0,0x76]), exp_a=0x00, exp_z=True)

# --- CMP B (0xB8): A не меняется ---
check("CMP B: 05>03", run_prog([0x3E,0x05,0x06,0x03,0xB8,0x76]), exp_a=0x05, exp_c=False, exp_z=False)
check("CMP B: 03<05", run_prog([0x3E,0x03,0x06,0x05,0xB8,0x76]), exp_a=0x03, exp_c=True, exp_z=False)
check("CMP B: 05=05", run_prog([0x3E,0x05,0x06,0x05,0xB8,0x76]), exp_a=0x05, exp_c=False, exp_z=True)

# --- ADI (0xC6) ---
check("ADI: 0F+01", run_prog([0x3E,0x0F,0xC6,0x01,0x76]), exp_a=0x10, exp_ac=True, exp_c=False)
check("ADI: FF+01", run_prog([0x3E,0xFF,0xC6,0x01,0x76]), exp_a=0x00, exp_c=True, exp_z=True)

# --- ACI (0xCE) ---
check("ACI: 0F+01+C0", run_prog([0x3E,0x0F,0xCE,0x01,0x76]), exp_a=0x10, exp_ac=True, exp_c=False)
check("ACI: 0F+01+C1", run_prog([0x3E,0x0F,0x37,0xCE,0x01,0x76]), exp_a=0x11, exp_ac=True, exp_c=False)

# --- SUI (0xD6) ---
check("SUI: 05-03", run_prog([0x3E,0x05,0xD6,0x03,0x76]), exp_a=0x02, exp_c=False)
check("SUI: 03-05", run_prog([0x3E,0x03,0xD6,0x05,0x76]), exp_a=0xFE, exp_c=True, exp_s=True)

# --- SBI (0xDE) ---
check("SBI: 05-03-C0", run_prog([0x3E,0x05,0xDE,0x03,0x76]), exp_a=0x02, exp_c=False)
check("SBI: 03-05-C1", run_prog([0x3E,0x03,0x37,0xDE,0x05,0x76]), exp_a=0xFD, exp_c=True, exp_s=True)

# --- ANI (0xE6) ---
check("ANI: 08&00", run_prog([0x3E,0x08,0xE6,0x00,0x76]), exp_a=0x00, exp_ac=False, exp_z=True)
check("ANI: 08&08", run_prog([0x3E,0x08,0xE6,0x08,0x76]), exp_a=0x08, exp_ac=True)
check("ANI: FF&07", run_prog([0x3E,0xFF,0xE6,0x07,0x76]), exp_a=0x07, exp_ac=False)

# --- XRI (0xEE) ---
check("XRI: 0F^03", run_prog([0x3E,0x0F,0xEE,0x03,0x76]), exp_a=0x0C)
check("XRI: FF^FF", run_prog([0x3E,0xFF,0xEE,0xFF,0x76]), exp_a=0x00, exp_z=True)

# --- ORI (0xF6) ---
check("ORI: 05|03", run_prog([0x3E,0x05,0xF6,0x03,0x76]), exp_a=0x07)
check("ORI: 00|00", run_prog([0x3E,0x00,0xF6,0x00,0x76]), exp_a=0x00, exp_z=True)

# --- CPI (0xFE): A не меняется ---
check("CPI: 10<20", run_prog([0x3E,0x10,0xFE,0x20,0x76]), exp_a=0x10, exp_c=True, exp_z=False)
check("CPI: 20>10", run_prog([0x3E,0x20,0xFE,0x10,0x76]), exp_a=0x20, exp_c=False, exp_z=False)
check("CPI: 10=10", run_prog([0x3E,0x10,0xFE,0x10,0x76]), exp_a=0x10, exp_c=False, exp_z=True)

# --- DAA (0x27) ---
check("DAA: 15", run_prog([0x3E,0x15,0x27,0x76]), exp_a=0x15)
check("DAA: 1A->20", run_prog([0x3E,0x1A,0x27,0x76]), exp_a=0x20)
check("DAA: 05+07=12", run_prog([0x3E,0x05,0xC6,0x07,0x27,0x76]), exp_a=0x12, exp_ac=True)
check("DAA: 09+01=10", run_prog([0x3E,0x09,0xC6,0x01,0x27,0x76]), exp_a=0x10, exp_ac=True)

# --- RLC (0x07) ---
check("RLC: 80->01", run_prog([0x3E,0x80,0x07,0x76]), exp_a=0x01, exp_c=True)
check("RLC: 01->02", run_prog([0x3E,0x01,0x07,0x76]), exp_a=0x02, exp_c=False)

# --- RRC (0x0F) ---
check("RRC: 01->80", run_prog([0x3E,0x01,0x0F,0x76]), exp_a=0x80, exp_c=True)
check("RRC: 80->40", run_prog([0x3E,0x80,0x0F,0x76]), exp_a=0x40, exp_c=False)

# --- RAL (0x17) ---
check("RAL: 80,C0->00", run_prog([0x3E,0x80,0x17,0x76]), exp_a=0x00, exp_c=True)
check("RAL: 80,C1->01", run_prog([0x3E,0x80,0x37,0x17,0x76]), exp_a=0x01, exp_c=True)

# --- RAR (0x1F) ---
check("RAR: 01,C0->00", run_prog([0x3E,0x01,0x1F,0x76]), exp_a=0x00, exp_c=True)
check("RAR: 01,C1->80", run_prog([0x3E,0x01,0x37,0x1F,0x76]), exp_a=0x80, exp_c=True)

# --- Parity (ORA A=0xB7 ставит флаги по значению A) ---
check("Parity: 03 even", run_prog([0x3E,0x03,0xB7,0x76]), exp_p=True)
check("Parity: 01 odd", run_prog([0x3E,0x01,0xB7,0x76]), exp_p=False)
check("Parity: 0F even", run_prog([0x3E,0x0F,0xB7,0x76]), exp_p=True)
check("Parity: FF even", run_prog([0x3E,0xFF,0xB7,0x76]), exp_p=True)

print(f"\n{'='*50}")
print(f"РЕЗУЛЬТАТ: {passed} пройдено, {failed} провалено")
print(f"{'='*50}")
sys.exit(1 if failed else 0)
